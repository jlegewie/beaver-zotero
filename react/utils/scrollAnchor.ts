/**
 * The reader's place in a thread, recorded by what they were reading rather
 * than by a pixel offset.
 *
 * The same thread is shown in panes of different widths — the library and
 * reader sidebars each take the width of the Zotero pane they live in, and the
 * reader can drag either. Text wraps differently at each width, so the same
 * `scrollTop` lands on different content. An anchor names the element at the
 * top of the viewport and how far into it the reader was, as a fraction of its
 * height, which survives that re-wrap.
 */

/** One element of the thread that contained the top of the viewport. */
export interface ScrollAnchorLevel {
    /** The element's id. */
    id: string;
    /**
     * Where the top of the viewport sat in the element, as a fraction of its
     * height: 0 at its top, 1 at its bottom. Slightly negative when the
     * viewport top sat in the gap just above it.
     */
    fraction: number;
}

export interface ScrollAnchor {
    /**
     * The elements at the top of the viewport, outermost (the run) first. The
     * innermost one still rendered when the thread is shown again is used, so
     * a part that no longer renders (a collapsed tool result) falls back to
     * the run or response that holds it.
     */
    levels: ScrollAnchorLevel[];
    /** The raw offset, for when none of the elements is rendered any more. */
    scrollTop: number;
}

/**
 * Elements whose ids derive from thread data, so the same element carries the
 * same id each time the thread is rendered. Ids generated by React (`useId`)
 * change between mounts and must not be anchored to.
 */
const ANCHOR_SELECTOR = [
    '[id^="run-"]',
    '[id^="user-request-"]',
    '[id^="response-"]',
    '[id^="tool-"]',
    '[id^="thinking-content-"]',
].join(',');

/**
 * The child of `content` that holds the line `y`, or the first one below it
 * when `y` falls in a gap. The children are stacked in document order, so a
 * binary search reads only a handful of boxes even in a long thread.
 */
function findChildAtLine(content: Element, y: number): HTMLElement | null {
    const children = content.children;
    let low = 0;
    let high = children.length - 1;
    let found: HTMLElement | null = null;
    while (low <= high) {
        const mid = (low + high) >> 1;
        const child = children[mid] as HTMLElement;
        if (child.getBoundingClientRect().bottom > y) {
            found = child;
            high = mid - 1;
        } else {
            low = mid + 1;
        }
    }
    return found;
}

function levelFor(element: HTMLElement, y: number): ScrollAnchorLevel | null {
    const rect = element.getBoundingClientRect();
    if (!element.id || rect.height <= 0) return null;
    return { id: element.id, fraction: (y - rect.top) / rect.height };
}

/**
 * Record what the top of `container`'s viewport is showing.
 *
 * Expects the thread's layout: `container` scrolls, and its first child holds
 * one element per run. Reads layout, so call it where layout is already
 * settled — a scroll handler — rather than right after a render.
 *
 * @returns Null when the container is not displayed. With nothing anchorable
 * at the top of the viewport, an anchor holding only the raw offset.
 */
export function captureScrollAnchor(container: HTMLElement): ScrollAnchor | null {
    if (container.clientHeight === 0) return null;
    const anchor: ScrollAnchor = { levels: [], scrollTop: container.scrollTop };
    const content = container.firstElementChild;
    if (!content) return anchor;

    const y = container.getBoundingClientRect().top;
    const run = findChildAtLine(content, y);
    if (!run) return anchor;

    const runLevel = run.matches(ANCHOR_SELECTOR) ? levelFor(run, y) : null;
    if (runLevel) anchor.levels.push(runLevel);

    // Anchorable elements inside the run that contain the line. Boxes holding
    // one line are nested in one another, so document order is outermost first.
    const candidates = run.querySelectorAll<HTMLElement>(ANCHOR_SELECTOR);
    for (let i = 0; i < candidates.length; i++) {
        const element = candidates[i];
        const rect = element.getBoundingClientRect();
        if (rect.top <= y && rect.bottom > y) {
            const level = levelFor(element, y);
            if (level) anchor.levels.push(level);
        }
    }
    return anchor;
}

/**
 * The `scrollTop` that puts `anchor` back at the top of `container`'s
 * viewport, at whatever width the container now has.
 *
 * Uses the innermost recorded element that is rendered and laid out; falls
 * back to the recorded offset when none is. Clamped to the offsets the
 * container can take, so the result compares honestly with `scrollTop`.
 */
export function resolveScrollAnchor(container: HTMLElement, anchor: ScrollAnchor): number {
    const maxScrollTop = Math.max(container.scrollHeight - container.clientHeight, 0);
    const clamp = (scrollTop: number) => Math.min(Math.max(scrollTop, 0), maxScrollTop);
    const containerTop = container.getBoundingClientRect().top;
    for (let i = anchor.levels.length - 1; i >= 0; i--) {
        const { id, fraction } = anchor.levels[i];
        const element = container.ownerDocument.getElementById(id);
        if (!element || !container.contains(element)) continue;
        const rect = element.getBoundingClientRect();
        if (rect.height <= 0) continue;
        return clamp(rect.top - containerTop + container.scrollTop + fraction * rect.height);
    }
    return clamp(anchor.scrollTop);
}
