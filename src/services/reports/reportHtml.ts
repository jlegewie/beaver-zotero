/**
 * Builds self-contained HTML reports that render inside Zotero's snapshot reader.
 *
 * The reader loads snapshots in a sandboxed iframe under a fixed CSP:
 *
 *   default-src zotero:; img-src zotero: data: blob:;
 *   style-src zotero: data: 'unsafe-inline'; font-src zotero: resource: data: blob:;
 *   script-src 'unsafe-eval'; child-src 'none'; form-action 'none'
 *
 * Consequences this module is built around:
 *   - Author JavaScript never runs. Anything dynamic must be precomputed here.
 *   - No network of any kind. Images must be inline SVG or data: URIs.
 *   - Inline <style> and style attributes are allowed, so full CSS layout works.
 *
 * The reader also themes snapshots automatically, and how it does that depends on
 * the top-level CSS rule count (see CSS_RULE_BUDGET). Staying under the budget keeps
 * documents on the Dark Reader path, which remaps colors while preserving contrast
 * relationships. The stylesheet below is written to survive either path.
 *
 * This module is deliberately free of Zotero APIs: callers pass prebuilt link URIs.
 */

/**
 * The reader counts top-level rules per author stylesheet and switches to a static
 * theme above 500. The static theme forces `background-color: transparent !important`
 * and a single text color onto every element, which flattens a designed palette.
 * Reports stay well under the threshold so the nicer dynamic path is always used.
 */
export const CSS_RULE_BUDGET = 500;

export interface ReportCitation {
    /** Display label, e.g. "Anderson & Lee (2019)". */
    label: string;
    /** Full reference line rendered under the label. */
    reference?: string;
    /** zotero://select URI that reveals the item in the library. */
    selectUri?: string | null;
    /** zotero://open URI for a file attachment, when one exists. */
    openUri?: string | null;
    /** Optional locator shown next to the open link, e.g. "p. 14". */
    locator?: string | null;
}

export type ReportBlock =
    | { type: 'paragraph'; text: string }
    | { type: 'list'; ordered?: boolean; items: string[] }
    | { type: 'table'; columns: string[]; rows: string[][] }
    | { type: 'bar_chart'; caption?: string; series: { label: string; value: number }[]; unit?: string }
    | { type: 'callout'; variant: 'note' | 'warning'; title: string; text: string }
    | { type: 'citations'; entries: ReportCitation[] };

export interface ReportSection {
    heading: string;
    blocks: ReportBlock[];
}

export interface ReportSpec {
    title: string;
    subtitle?: string;
    /** Free-text provenance line, e.g. "Generated by Beaver on 3 August 2026". */
    provenance?: string;
    sections: ReportSection[];
    footerNote?: string;
}

export interface BuiltReport {
    html: string;
    /** Top-level rule count of the emitted stylesheet, for budget assertions. */
    cssRuleCount: number;
}

const ESCAPE_MAP: Record<string, string> = {
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;',
};

/** Escapes text for HTML body/attribute context. All model-authored text goes through this. */
export function escapeHtml(value: string): string {
    return String(value).replace(/[&<>"']/g, (ch) => ESCAPE_MAP[ch]);
}

/**
 * Only `zotero:` links are emitted. Anything else is rendered as plain text so a
 * generated report can never become a clickable path to an arbitrary destination.
 */
function safeUri(uri: string | null | undefined): string | null {
    if (!uri) return null;
    return /^zotero:\/\//i.test(uri) ? uri : null;
}

