/** Counts top-level rules the way the reader does (nested at-rule bodies are not counted). */
export function countTopLevelCssRules(css: string): number {
    let depth = 0;
    let count = 0;
    for (const ch of css) {
        if (ch === '{') {
            if (depth === 0) count++;
            depth++;
        } else if (ch === '}') {
            depth = Math.max(0, depth - 1);
        }
    }
    return count;
}

const CHART_FILLS = ['#2f5bd7', '#6d4bc4', '#0e7c86', '#a04a00', '#3f6212', '#9d174d'];

/**
 * Renders a bar chart as inline SVG with geometry computed here, since no script runs.
 *
 * Bars use explicit fills rather than `currentColor`: the reader's static theme sets
 * `color` on every element, which would otherwise repaint the whole chart one color.
 */
function renderBarChart(series: { label: string; value: number }[], unit?: string): string {
    if (!series.length) return '<p class="rp-empty rp-muted">No data.</p>';

    const width = 680;
    const rowHeight = 34;
    const gap = 10;
    const labelWidth = 190;
    // Values are right-aligned to the viewBox edge, so this only has to fit the
    // widest number. Units live in the caption rather than on every row, which
    // would otherwise overflow the viewBox and be clipped.
    const valueWidth = 52;
    const trackWidth = width - labelWidth - valueWidth;
    const height = series.length * (rowHeight + gap);
    const max = Math.max(...series.map((s) => (Number.isFinite(s.value) ? Math.abs(s.value) : 0)), 1);

    const bars = series.map((point, i) => {
        const value = Number.isFinite(point.value) ? point.value : 0;
        const y = i * (rowHeight + gap);
        const barWidth = Math.max(2, Math.round((Math.abs(value) / max) * trackWidth));
        const fill = CHART_FILLS[i % CHART_FILLS.length];
        return [
            `<text x="0" y="${y + rowHeight / 2 + 4}" font-size="13" fill="#5b6472">${escapeHtml(point.label)}</text>`,
            `<rect x="${labelWidth}" y="${y + 4}" width="${trackWidth}" height="${rowHeight - 8}" rx="4" fill="#eef1f5"></rect>`,
            `<rect x="${labelWidth}" y="${y + 4}" width="${barWidth}" height="${rowHeight - 8}" rx="4" fill="${fill}"></rect>`,
            `<text x="${width}" y="${y + rowHeight / 2 + 4}" font-size="13" text-anchor="end" fill="#16181d">${escapeHtml(String(value))}</text>`,
        ].join('');
    });

    const summary = series.map((s) => `${s.label}: ${s.value}${unit ? ` ${unit}` : ''}`).join('; ');
    return (
        `<svg viewBox="0 0 ${width} ${height}" role="img" aria-label="${escapeHtml(summary)}" ` +
        `xmlns="http://www.w3.org/2000/svg">${bars.join('')}</svg>`
    );
}

function renderCitation(entry: ReportCitation): string {
    const selectUri = safeUri(entry.selectUri);
    const openUri = safeUri(entry.openUri);

    const links: string[] = [];
    if (selectUri) {
        links.push(`<a href="${escapeHtml(selectUri)}">Show in library</a>`);
    }
    if (openUri) {
        const locator = entry.locator ? ` (${escapeHtml(entry.locator)})` : '';
        links.push(`<a href="${escapeHtml(openUri)}">Open attachment</a>${locator}`);
    }

    return [
        '<li class="rp-cite">',
        `<div class="rp-cite-label">${escapeHtml(entry.label)}</div>`,
        entry.reference ? `<div class="rp-cite-ref rp-muted">${escapeHtml(entry.reference)}</div>` : '',
        links.length ? `<div class="rp-cite-links">${links.join('<span class="rp-sep rp-muted">·</span>')}</div>` : '',
        '</li>',
    ].join('');
}

function renderBlock(block: ReportBlock): string {
    switch (block.type) {
        case 'paragraph':
            return `<p>${escapeHtml(block.text)}</p>`;

        case 'list': {
            const tag = block.ordered ? 'ol' : 'ul';
            const items = block.items.map((item) => `<li>${escapeHtml(item)}</li>`).join('');
            return `<${tag}>${items}</${tag}>`;
        }

        case 'table': {
            const head = block.columns.map((c) => `<th>${escapeHtml(c)}</th>`).join('');
            const body = block.rows
                .map((row) => `<tr>${row.map((cell) => `<td>${escapeHtml(cell)}</td>`).join('')}</tr>`)
                .join('');
            return `<div class="rp-table-wrap"><table><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table></div>`;
        }

        case 'bar_chart': {
            const captionText = [block.caption, block.unit ? `Values in ${block.unit}.` : '']
                .filter(Boolean)
                .join(' ');
            const caption = captionText
                ? `<p class="rp-caption rp-muted">${escapeHtml(captionText)}</p>`
                : '';
            return `<figure class="rp-figure">${renderBarChart(block.series, block.unit)}${caption}</figure>`;
        }

        case 'callout':
            return [
                `<div class="rp-callout rp-callout--${block.variant === 'warning' ? 'warn' : 'note'}">`,
                `<p class="rp-callout-title">${escapeHtml(block.title)}</p>`,
                `<p>${escapeHtml(block.text)}</p>`,
                '</div>',
            ].join('');

        case 'citations':
            if (!block.entries.length) {
                return '<p class="rp-empty rp-muted">No sources cited.</p>';
            }
            return `<ul class="rp-cites">${block.entries.map(renderCitation).join('')}</ul>`;

        default:
            return '';
    }
}

/**
 * Builds the complete document. The output contains no <script>, no external
 * references, and no resources beyond what is inlined here.
 */
export function buildReportHtml(spec: ReportSpec): BuiltReport {
    const sections = spec.sections
        .map((section) => {
            const blocks = section.blocks.map(renderBlock).join('\n');
            return `<section><h2 class="rp-muted">${escapeHtml(section.heading)}</h2>\n${blocks}</section>`;
        })
        .join('\n');

    const html = [
        '<!DOCTYPE html>',
        '<html lang="en">',
        '<head>',
        '<meta charset="utf-8">',
        `<title>${escapeHtml(spec.title)}</title>`,
        `<style>\n${REPORT_CSS}\n</style>`,
        '</head>',
        '<body>',
        '<article class="rp">',
        `<h1 class="rp-title">${escapeHtml(spec.title)}</h1>`,
        spec.subtitle ? `<p class="rp-subtitle rp-muted">${escapeHtml(spec.subtitle)}</p>` : '',
        spec.provenance ? `<p class="rp-provenance rp-muted">${escapeHtml(spec.provenance)}</p>` : '',
        sections,
        spec.footerNote ? `<footer class="rp-footer rp-muted">${escapeHtml(spec.footerNote)}</footer>` : '',
        '</article>',
        '</body>',
        '</html>',
        '',
    ]
        .filter(Boolean)
        .join('\n');

    return { html, cssRuleCount: countTopLevelCssRules(REPORT_CSS) };
}
